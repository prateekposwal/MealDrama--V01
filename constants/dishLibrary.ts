// ─────────────────────────────────────────────────────────────────────────────
// MealDrama Dish Library — Scalable to 10,000 dishes via variation dimensions
// Each base dish expands by: cooking style × meal context × region override × add-ons
// ─────────────────────────────────────────────────────────────────────────────

export type Region = 'north' | 'south' | 'west' | 'east' | 'central' | 'northeast';
export type Category = 'breakfast' | 'lunch' | 'dinner' | 'snacks' | 'winter-lunch' | 'summer-lunch' | 'winter-dinner' | 'summer-dinner';
export type DishType = 'veg' | 'non-veg' | 'vegan' | 'eggitarian';
export type Weight = 'light' | 'medium' | 'heavy';

export type IngredientCategory = 'produce' | 'dairy' | 'grains' | 'proteins' | 'spices' | 'pantry' | 'breads';

export interface Ingredient {
    name: string;
    quantity: number;
    unit: string;
    category: IngredientCategory;
    inStock?: boolean;
}

export interface DishVariant {
    id: string;
    name: string;
    cookingStyle?: string; // tadka / roast / fried / steamed
    addOn?: string;        // with rice / with roti / standalone
    mealContext?: Category;
    regionOverride?: string; // "Kerala" or "Bengal" fish curry
    baseStyle?: string;      // Abstract style used by UI (e.g. 'dry', 'gravy', 'porridge')
    // Optional: regional accompaniments (sides or breads) that pair with this variant
    accompaniments?: string[];
    // Ingredients for shopping list generation
    ingredients?: Ingredient[];
}

export interface Dish {
    id: string;
    name: string;
    icon: string;
    region: Region;
    states: string[];
    category: Category[];
    type: DishType;
    weight: Weight;
    nutrition: string[];
    tags: string[];
    variants: DishVariant[];
    // Optional: seasonal availability or regional nuances
    season?: string[];
}

// ─── Helper: auto-generate variants ──────────────────────────────────────────
const addOnVariants = (base: string, id: string): DishVariant[] => [
    { id: `${id}-rice`, name: `${base} + Rice`, addOn: 'with rice', mealContext: 'lunch' },
    { id: `${id}-roti`, name: `${base} + Roti`, addOn: 'with roti', mealContext: 'dinner' },
    { id: `${id}-bowl`, name: `${base} Bowl`, addOn: 'standalone', mealContext: 'lunch' },
    { id: `${id}-lite`, name: `${base} Lite (Dinner)`, addOn: 'light portion', mealContext: 'dinner' },
    { id: `${id}-thali`, name: `${base} Thali`, addOn: 'thali set', mealContext: 'lunch' },
];

const cookingVariants = (base: string, id: string, styles: string[]): DishVariant[] =>
    styles.map(style => ({ id: `${id}-${style.toLowerCase()}`, name: `${base} ${style}`, cookingStyle: style }));

