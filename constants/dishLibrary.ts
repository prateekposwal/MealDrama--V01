export const getDishesByRegion = (region: Region) =>
    DISH_LIBRARY.filter(d => d.region === region);

export const getDishesByState = (state: string) =>
    DISH_LIBRARY.filter(d => d.states.includes(state));

export const getDishesByCategory = (category: Category) =>
    DISH_LIBRARY.filter(d => d.category.includes(category));

export const getDishesByStateAndCategory = (state: string, category: Category) =>
    DISH_LIBRARY.filter(d => d.states.includes(state) && d.category.includes(category));

export const searchDishes = (query: string) => {
    const q = query.toLowerCase();
    return DISH_LIBRARY.filter(d =>
        d.name.toLowerCase().includes(q) ||
        d.states.some(s => s.toLowerCase().includes(q)) ||
        d.tags.some(t => t.includes(q))
    );
};

