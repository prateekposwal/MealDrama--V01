import { PrismaClient } from '@prisma/client';
const p = new PrismaClient();
const meals = await p.meal.count();
const variants = await p.mealVariant.count();
const ingredients = await p.ingredient.count();
const users = await p.user.count();
const hasPoha = await p.meal.findUnique({ where: { id: 'poha-mp' }, select: { id: true, name: true } });
const hasDalTadka = await p.meal.findUnique({ where: { id: 'dal-tadka-central' }, select: { id: true, name: true } });
console.log(JSON.stringify({ meals, variants, ingredients, users, hasPoha, hasDalTadka }, null, 2));
await p.$disconnect();
